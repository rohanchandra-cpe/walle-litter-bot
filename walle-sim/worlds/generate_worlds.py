"""Generate the Gazebo test environments for the three research questions.

    python3 walle-sim/worlds/generate_worlds.py      # rewrites worlds/*.sdf and world_info.yaml

Every world follows draft Section IV-C: one indoor area, a smooth wooden floor, steady
lighting, nothing in front of the sensors but the intended target. The generated files
are committed, so you only run this after changing a dimension here.

  rq1_lane         RQ1: the 1 m x 0.3 m lane, start line, 50 cm target line, +/-5 cm marks
  rq2_protractor   RQ2: a printed protractor (1 deg graduations drawn every 5 deg)
  motion_area      RQ1 + RQ2 side by side, for running a whole session's schedule,
                   which interleaves straight runs and turns
  rq3_ranging      RQ3: a plain room, the 0 and 20 deg rays taped on the floor at the
                   eight test distances, and the four controlled objects (plus the
                   calibration ball) parked out of view behind the robot
  rq3_ranging_dim  RQ3 with a quarter of the light: a color-mask stress condition
  inspection_room  agent and tool testing (ROSA): litter, a bin, and an obstacle

world_info.yaml tells launch/sim.launch.py where to spawn the robot and tells
harness/sim_trials.py where the lane, the protractor, the rays and the objects are.
"""

import math
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))

# ===== The RQ3 objects (draft IV-B), as simple shapes =====
# The true range is measured to the nearest surface, so each is a vertical cylinder or
# a sphere: its nearest surface on any ray is exactly `radius` before its center.
OBJECTS = {
    "red_cup":        {"color": "red",    "rgb": [0.85, 0.10, 0.10], "shape": "cylinder",
                       "radius": 0.040, "height": 0.095, "note": "paper cup"},
    "blue_bottle":    {"color": "blue",   "rgb": [0.10, 0.25, 0.85], "shape": "cylinder",
                       "radius": 0.0325, "height": 0.205, "note": "upright 500 mL bottle"},
    "green_bin":      {"color": "green",  "rgb": [0.10, 0.65, 0.20], "shape": "cylinder",
                       "radius": 0.100, "height": 0.200, "note": "about 20 cm bin"},
    "yellow_wrapper": {"color": "yellow", "rgb": [0.95, 0.85, 0.10], "shape": "sphere",
                       "radius": 0.025, "height": 0.050,
                       "note": "crumpled wrapper; short enough to miss the acoustic beam far out"},
    "red_ball":       {"color": "red",    "rgb": [0.85, 0.10, 0.10], "shape": "sphere",
                       "radius": 0.035, "height": 0.070,
                       "note": "depth calibration object only (ranging.calibration_object)"},
}

# The shared sensor reference plane: camera and HC-SR04 sit at x = camera_x in base_link
SENSOR_X = 0.07
RQ3_DISTANCES = [0.30, 0.50, 0.75, 1.00, 1.25, 1.50, 1.75, 2.00]
RQ3_ANGLES = [0, 20]

WOOD = [0.72, 0.55, 0.36]
TAPE = [0.08, 0.08, 0.08]
WALL = [0.82, 0.82, 0.80]


# ===== SDF pieces =====
def header(name, ambient=0.6, sun=0.9):
    return f"""<?xml version="1.0" ?>
<!-- Generated by walle-sim/worlds/generate_worlds.py: edit that script, not this file. -->
<sdf version="1.8">
  <world name="{name}">

    <physics name="2ms" type="ignored">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="ignition-gazebo-imu-system" name="ignition::gazebo::systems::Imu"/>

    <scene>
      <ambient>{ambient} {ambient} {ambient} 1</ambient>
      <background>0.75 0.85 0.95 1</background>
      <shadows>false</shadows>
    </scene>

    <!-- Ceiling lighting, held constant (draft IV-C) -->
    <light type="directional" name="ceiling">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 3 0 0 0</pose>
      <diffuse>{sun} {sun} {sun} 1</diffuse>
      <specular>0.1 0.1 0.1 1</specular>
      <direction>-0.2 0.1 -1.0</direction>
    </light>

    <!-- Smooth wooden floor -->
    <model name="floor">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          {material(WOOD)}
        </visual>
      </link>
    </model>
"""


FOOTER = """
  </world>
</sdf>
"""


def material(rgb, alpha=1.0):
    r, g, b = rgb
    return (f"<material><ambient>{r} {g} {b} {alpha}</ambient>"
            f"<diffuse>{r} {g} {b} {alpha}</diffuse><specular>0.05 0.05 0.05 1</specular></material>")


def mark(name, x, y, yaw, length, width, rgb=TAPE):
    """A flat strip of tape on the floor: visual only, so the robot drives over it."""
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.4f} {y:.4f} 0.0005 0 0 {yaw:.5f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>{length:.4f} {width:.4f} 0.001</size></box></geometry>
          {material(rgb)}
        </visual>
      </link>
    </model>"""


def wall(name, x, y, sx, sy, height=1.5, rgb=WALL):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {height / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx} {sy} {height}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {height}</size></box></geometry>
          {material(rgb)}
        </visual>
      </link>
    </model>"""


def room(x_min, x_max, y_min, y_max, height=1.5):
    cx, cy = (x_min + x_max) / 2, (y_min + y_max) / 2
    lx, ly = x_max - x_min + 0.05, y_max - y_min + 0.05
    return "".join([
        wall("wall_front", x_max, cy, 0.05, ly, height),
        wall("wall_back", x_min, cy, 0.05, ly, height),
        wall("wall_left", cx, y_max, lx, 0.05, height),
        wall("wall_right", cx, y_min, lx, 0.05, height),
    ])


def obj(name, x, y, static=True):
    o = OBJECTS[name]
    if o["shape"] == "cylinder":
        geom = f"<cylinder><radius>{o['radius']}</radius><length>{o['height']}</length></cylinder>"
        z = o["height"] / 2
    else:
        geom = f"<sphere><radius>{o['radius']}</radius></sphere>"
        z = o["radius"]
    return f"""
    <!-- {o['note']} -->
    <model name="{name}">
      <static>{'true' if static else 'false'}</static>
      <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry></collision>
        <visual name="visual">
          <geometry>{geom}</geometry>
          {material(o['rgb'])}
        </visual>
      </link>
    </model>"""


def box_obstacle(name, x, y, sx, sy, sz, rgb):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {sz / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          {material(rgb)}
        </visual>
      </link>
    </model>"""


# ===== RQ1: the lane =====
LANE = {"length": 1.0, "half_width": 0.15, "back": 0.2}   # lane from x = -0.2 to 0.8


def lane(ox, oy, prefix="lane"):
    """The 1 m x 0.3 m lane. The axle pin starts on the start line at (ox, oy), facing +x."""
    L, hw, back = LANE["length"], LANE["half_width"], LANE["back"]
    x0, x1 = ox - back, ox - back + L
    cx = (x0 + x1) / 2
    parts = [
        mark(f"{prefix}_edge_left", cx, oy + hw, 0, L, 0.012),
        mark(f"{prefix}_edge_right", cx, oy - hw, 0, L, 0.012),
        mark(f"{prefix}_start_line", ox, oy, math.pi / 2, 2 * hw, 0.006),
        mark(f"{prefix}_target_50cm", ox + 0.50, oy, math.pi / 2, 2 * hw, 0.006, [0.8, 0.1, 0.1]),
        mark(f"{prefix}_tol_45cm", ox + 0.45, oy, math.pi / 2, 2 * hw, 0.003, [0.35, 0.35, 0.35]),
        mark(f"{prefix}_tol_55cm", ox + 0.55, oy, math.pi / 2, 2 * hw, 0.003, [0.35, 0.35, 0.35]),
    ]
    # Lateral tolerance (+/- 5 cm) as thin lines, and a dashed centerline
    for side, y in (("left", oy + 0.05), ("right", oy - 0.05)):
        parts.append(mark(f"{prefix}_tol_{side}", cx, y, 0, L, 0.002, [0.35, 0.35, 0.35]))
    for i, x in enumerate(frange(x0 + 0.025, x1, 0.05)):
        parts.append(mark(f"{prefix}_center_{i:02d}", x, oy, 0, 0.025, 0.003))
    return "".join(parts)


def frange(start, stop, step):
    out, x = [], start
    while x < stop - 1e-9:
        out.append(x)
        x += step
    return out


# ===== RQ2: the protractor =====
PROTRACTOR_RADIUS = 0.22


def protractor(cx, cy, prefix="protractor"):
    parts = [f"""
    <model name="{prefix}_sheet">
      <static>true</static>
      <pose>{cx} {cy} 0.0003 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry><cylinder><radius>{PROTRACTOR_RADIUS}</radius><length>0.0006</length></cylinder></geometry>
          {material([0.97, 0.97, 0.95])}
        </visual>
      </link>
    </model>"""]
    for deg in range(0, 360, 5):
        length = 0.07 if deg % 90 == 0 else 0.04 if deg % 10 == 0 else 0.02
        r = PROTRACTOR_RADIUS - length / 2 - 0.005
        a = math.radians(deg)
        rgb = [0.8, 0.1, 0.1] if deg == 0 else TAPE
        parts.append(mark(f"{prefix}_tick_{deg:03d}", cx + r * math.cos(a), cy + r * math.sin(a),
                          a, length, 0.003 if deg % 10 else 0.004, rgb))
    parts.append(mark(f"{prefix}_zero_ray", cx + PROTRACTOR_RADIUS / 2, cy, 0,
                      PROTRACTOR_RADIUS, 0.002, [0.8, 0.1, 0.1]))
    return "".join(parts)


# ===== RQ3: rays and placement marks =====
def rays(prefix="ray"):
    parts = [mark(f"{prefix}_reference_plane", SENSOR_X, 0.0, math.pi / 2, 0.6, 0.004,
                  [0.1, 0.3, 0.8])]
    for angle in RQ3_ANGLES:
        a = math.radians(angle)
        length = max(RQ3_DISTANCES) + 0.15
        parts.append(mark(f"{prefix}_{angle:02d}deg", SENSOR_X + length / 2 * math.cos(a),
                          length / 2 * math.sin(a), a, length, 0.003))
        for d in RQ3_DISTANCES:
            parts.append(mark(f"{prefix}_{angle:02d}deg_{int(round(d * 100)):03d}cm",
                              SENSOR_X + d * math.cos(a), d * math.sin(a), a + math.pi / 2,
                              0.04, 0.003, [0.8, 0.1, 0.1]))
    return "".join(parts)


# Parking spots behind the robot: outside the camera view and the acoustic cone
STORAGE = {"red_cup": [-0.8, -0.6], "blue_bottle": [-0.8, -0.3], "green_bin": [-0.8, 0.05],
           "yellow_wrapper": [-0.8, 0.4], "red_ball": [-0.8, 0.65]}


# ===== the worlds =====
def write(name, body, ambient=0.6, sun=0.9):
    with open(os.path.join(HERE, f"{name}.sdf"), "w") as f:
        f.write(header(name, ambient, sun) + body + FOOTER)
    print(f"wrote worlds/{name}.sdf")


def main():
    info = {"objects": OBJECTS, "sensor_x": SENSOR_X,
            "rq3": {"distances_m": RQ3_DISTANCES, "angles_deg": RQ3_ANGLES}, "worlds": {}}
    lane_info = dict(LANE)

    write("rq1_lane", lane(0.0, 0.0))
    info["worlds"]["rq1_lane"] = {"spawn": [0.0, 0.0, 0.0], "lane": lane_info,
                                  "view": {"target": [0.3, 0.0, 0.0], "offset": [-0.5, -0.8, 0.6]},
                                  "anchors": {"lane_start": [0.0, 0.0, 0.0]}}

    write("rq2_protractor", protractor(0.0, 0.0))
    info["worlds"]["rq2_protractor"] = {"spawn": [0.0, 0.0, 0.0],
                                        "view": {"target": [0.0, 0.0, 0.0], "offset": [-0.4, -0.5, 0.6]},
                                        "anchors": {"protractor": [0.0, 0.0, 0.0]}}

    write("motion_area", lane(0.0, 0.0) + protractor(0.0, 0.8))
    info["worlds"]["motion_area"] = {"spawn": [0.0, 0.0, 0.0], "lane": lane_info,
                                     "view": {"target": [0.3, 0.4, 0.0], "offset": [-0.6, -1.1, 0.9]},
                                     "anchors": {"lane_start": [0.0, 0.0, 0.0],
                                                 "protractor": [0.0, 0.8, 0.0]}}

    rq3_body = room(-1.2, 3.2, -1.6, 1.6) + rays() + "".join(
        obj(name, *STORAGE[name]) for name in OBJECTS)
    rq3_info = {"spawn": [0.0, 0.0, 0.0], "anchors": {"sensor_station": [0.0, 0.0, 0.0]},
                "view": {"target": [1.0, 0.2, 0.0], "offset": [-1.6, -1.4, 1.4]},
                "storage": STORAGE}
    write("rq3_ranging", rq3_body)
    info["worlds"]["rq3_ranging"] = rq3_info
    write("rq3_ranging_dim", rq3_body, ambient=0.15, sun=0.25)
    info["worlds"]["rq3_ranging_dim"] = dict(rq3_info)

    inspection = (room(-2.0, 2.0, -1.5, 1.5)
                  + box_obstacle("obstacle_box", 0.0, 0.0, 0.3, 0.3, 0.25, [0.45, 0.45, 0.5])
                  + obj("green_bin", 1.4, 0.9) + obj("red_cup", 0.6, -0.7)
                  + obj("blue_bottle", 1.5, -0.9) + obj("yellow_wrapper", 0.3, 0.6)
                  + mark("start_pad", -1.5, 0.0, 0.0, 0.3, 0.3, [0.2, 0.6, 0.3]))
    write("inspection_room", inspection)
    info["worlds"]["inspection_room"] = {"spawn": [-1.5, 0.0, 0.0],
                                         "view": {"target": [0.0, 0.0, 0.0], "offset": [-2.2, -2.0, 2.4]},
                                         "anchors": {"start": [-1.5, 0.0, 0.0]}}

    with open(os.path.join(HERE, "world_info.yaml"), "w") as f:
        f.write("# Generated by generate_worlds.py: positions are world-frame (x m, y m, yaw deg)\n")
        yaml.safe_dump(info, f, sort_keys=False)
    print("wrote worlds/world_info.yaml")


if __name__ == "__main__":
    main()
